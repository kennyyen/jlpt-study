function build(level: Level, entries: Entry[]): Word[] {
  // Ids are keyed on the word (not list position) so saved SRS progress
  // survives words being added or reordered.
  return entries.map(([word, kana, meaning]) => ({
    id: `${level}:${word}`,
    level,
    word,
    kana,
    meaning,
  }));
}

